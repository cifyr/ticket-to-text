// Deterministic PRNG so a given seed always produces the same deck — makes
// games reproducible in tests and lets both clients agree without a server.
// mulberry32: tiny, fast, good enough for shuffling a card deck (not crypto).
// Trivial to reimplement identically in Swift (UInt32 wrap-around arithmetic).

export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Fisher-Yates, driven by the seeded rng. Returns a new array.
export function shuffle<T>(items: readonly T[], rng: () => number): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
